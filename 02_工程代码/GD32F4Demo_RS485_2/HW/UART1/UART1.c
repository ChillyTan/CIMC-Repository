/*********************************************************************************************************
* 函数名称：ReadUART1Frame
* 函数功能：基于USART空闲中断读取一帧不定长数据
* 输入参数：pBuf-接收缓冲区，len-缓冲区长度
* 输出参数：pBuf-读取到的一帧数据
* 返 回 值：实际读取到的数据长度；没有完整帧时返回0
* 注    意：上位机连续发送一串字符，线路空闲后触发IDLE中断，本函数再一次性取出命令
*********************************************************************************************************/
unsigned int  ReadUART1Frame(unsigned char *pBuf, unsigned int len)
{
  unsigned int rLen = 0;

  if((pBuf == 0) || (len == 0))
  {
    return 0;
  }

  RS485_RX_ENABLE();

  if(s_iUARTIdleFlag)
  {
    s_iUARTIdleFlag = 0;
    rLen = DeQueue(&s_structUARTRecCirQue, pBuf, len);
  }

  return rLen;
}

