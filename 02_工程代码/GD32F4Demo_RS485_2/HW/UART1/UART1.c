void USART1_IRQHandler(void)            
{
  unsigned char  uData = 0;

  if(usart_interrupt_flag_get(USART1, USART_INT_FLAG_RBNE) != RESET)    //????????????????
  {                                                         
    usart_interrupt_flag_clear(USART1, USART_INT_FLAG_RBNE);            //???USART1???????
    uData = usart_data_receive(USART1);                                 //??USART1???????????????uData
                                                          
    WriteReceiveBuf(uData);                                             //?????????????????????????                                 
  }                                                         

  if(usart_interrupt_flag_get(USART1, USART_INT_FLAG_IDLE) != RESET)     //空闲中断
  {
    USART_STAT0(USART1);
    usart_data_receive(USART1);

    s_iUARTIdleFlag = 1;
  }
                                                            
  if(usart_interrupt_flag_get(USART1, USART_INT_FLAG_ERR_ORERR) == SET) //??????????1
  {                                                         
    usart_interrupt_flag_clear(USART1, USART_INT_FLAG_ERR_ORERR);       //????????????
    
    usart_data_receive(USART1);                                         //???USART_DR 
  }                                                         
                                                           
  if(usart_interrupt_flag_get(USART1, USART_INT_FLAG_TBE)!= RESET)      //???????????????
  {                       
    usart_interrupt_flag_clear(USART1, USART_INT_FLAG_TBE);             //?????????????
    NVIC_ClearPendingIRQ(USART1_IRQn);
                                   
    ReadSendBuf(&uData);                                 //???????????????????uData
                                                                    
    usart_data_transmit(USART1, uData);                  //??uData????USART_DR
                                                                                           
    if(QueueEmpty(&s_structUARTSendCirQue))              //???????????????
    {                                                              
      usart_interrupt_disable(USART1, USART_INT_TBE);    //????????????????????
      usart_interrupt_enable(USART1, USART_INT_TC);      //???????????????????
    }
  }
	
	/********************** ??????????? TC **********************/
  if(usart_interrupt_flag_get(USART1, USART_INT_FLAG_TC) != RESET)
  {
    usart_interrupt_flag_clear(USART1, USART_INT_FLAG_TC);
    usart_interrupt_disable(USART1, USART_INT_TC);
    RS485_RX_ENABLE();                    // ?????????????????PA1??????????????
    s_iUARTTxSts = UART_STATE_OFF;
  }
} 

