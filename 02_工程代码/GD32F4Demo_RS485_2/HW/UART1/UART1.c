/*********************************************************************************************************
* 函数名称：ProcUARTCmdTask
* 函数功能：处理上位机发送的不定长串口命令
* 输入参数：void
* 输出参数：void
* 返 回 值：void
* 注    意：USART1空闲中断置位后，ReadUART1Frame一次性读出完整命令
*********************************************************************************************************/
void ProcUARTCmdTask(void)
{
  u8 cmdBuf[64];
  unsigned int cmdLen = 0;

  cmdLen = ReadUART1Frame(cmdBuf, sizeof(cmdBuf) - 1);
  if(cmdLen == 0)
  {
    return;
  }

  cmdBuf[cmdLen] = '\0';

  //兼容回车换行
  while((cmdLen > 0) && ((cmdBuf[cmdLen - 1] == '\r') || (cmdBuf[cmdLen - 1] == '\n')))
  {
    cmdLen--;
    cmdBuf[cmdLen] = '\0';
  }

  if(strcmp((char *)cmdBuf, "config") == 0)
  {
    printf("ack\r\n");
  }
  else
  {
    printf("unknown cmd\r\n");
  }
}

